USE ds_sql_practice;

CREATE TABLE customers (customer_id INT PRIMARY KEY, name VARCHAR(100) NOT NULL, email VARCHAR(150) UNIQUE NOT NULL, city VARCHAR(80), signup_date DATE);
CREATE TABLE categories (category_id INT PRIMARY KEY, category_name VARCHAR(80) NOT NULL UNIQUE);
CREATE TABLE products (product_id INT PRIMARY KEY, product_name VARCHAR(120) NOT NULL, category_id INT NOT NULL, unit_price DECIMAL(10,2) NOT NULL, stock_qty INT NOT NULL, FOREIGN KEY(category_id) REFERENCES categories(category_id));
CREATE TABLE orders (order_id INT PRIMARY KEY, customer_id INT NOT NULL, order_date DATE NOT NULL, status ENUM('completed','pending','cancelled') NOT NULL, total_amount DECIMAL(12,2) NOT NULL, FOREIGN KEY(customer_id) REFERENCES customers(customer_id));
CREATE TABLE order_items (order_item_id INT PRIMARY KEY, order_id INT NOT NULL, product_id INT NOT NULL, quantity INT NOT NULL, unit_price DECIMAL(10,2) NOT NULL, line_total DECIMAL(12,2) NOT NULL, FOREIGN KEY(order_id) REFERENCES orders(order_id), FOREIGN KEY(product_id) REFERENCES products(product_id));
CREATE TABLE payments (payment_id INT PRIMARY KEY, order_id INT UNIQUE NOT NULL, payment_method VARCHAR(30), payment_status ENUM('paid','authorized','pending') NOT NULL, amount DECIMAL(12,2) NOT NULL, FOREIGN KEY(order_id) REFERENCES orders(order_id));

